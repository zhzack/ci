"""Self-service installer and uninstaller endpoints.

The platform serves its own bootstrap and lifecycle scripts so a fresh machine
can be set up with ONE command (no repo clone, no manual steps):

    Windows PowerShell:  irm http://<server>:8000/install.ps1 | iex
    Linux / macOS:       curl -fsSL http://<server>:8000/install.sh | bash

The scripts:
1. Check if the runner is already installed (avoids redundant downloads).
2. Auto-detect or prepare Python 3.9+ virtual environment.
3. Install/upgrade the mini-pipeline package.
4. Auto-register a background daemon / auto-start on boot.
5. Immediately launch the background daemon when a token is provided.

The platform also provides one-line uninstallation scripts:
    Windows:  irm http://<server>:8000/uninstall.ps1 | iex
    Linux:    curl -fsSL http://<server>:8000/uninstall.sh | bash
"""

