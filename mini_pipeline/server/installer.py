def _server_base_url(request: Request) -> str:
    param_server = request.query_params.get("server") or request.query_params.get("server_url")
    if param_server:
        return param_server.rstrip("/")

    forwarded = request.headers.get("x-forwarded-proto")
    scheme = forwarded or request.url.scheme
    forwarded_host = request.headers.get("x-forwarded-host")
    if forwarded_host:
        return f"{scheme}://{forwarded_host}"

    host = request.headers.get("host")
    if host and not host.startswith("api:") and host != "api":
        return f"{scheme}://{host}"

    base = str(request.base_url).rstrip("/")
    if "api:8000" in base or "http://api" in base:
        return "http://localhost:8000"
    return base


def _build_package_tarball() -> bytes:
    """Tar.gz of the platform package (mini_pipeline/ + pyproject.toml)."""
    import io

    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as tar:
        pyproject = _PACKAGE_ROOT / "pyproject.toml"
        tar.add(pyproject, arcname="pyproject.toml")
        package_dir = _PACKAGE_ROOT / "mini_pipeline"
        for path in sorted(package_dir.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(_PACKAGE_ROOT)
            if any(part in _TARBALL_EXCLUDE_PARTS for part in relative.parts):
                continue
            if path.name == ".DS_Store":
                continue
            tar.add(path, arcname=relative.as_posix())
    return buffer.getvalue()


@installer_router.get("/install/package.tar.gz", include_in_schema=False)
def install_package() -> Response:
    payload = _build_package_tarball()
    return Response(
        content=payload,
        media_type="application/gzip",
        headers={"Content-Disposition": 'attachment; filename="mini-pipeline.tar.gz"'},
    )


@installer_router.get("/install/runtimes/{filename}", include_in_schema=False)
def get_runtime_package(filename: str) -> Response:
    """Serve runtime packages from storage/environments/ or package hub."""
    pkg_dir = _PACKAGE_ROOT / "data" / "storage" / "environments"
    file_path = pkg_dir / filename
    if file_path.is_file():
        return Response(
            content=file_path.read_bytes(),
            media_type="application/gzip",
            headers={"Content-Disposition": f'attachment; filename="{filename}"'},
        )
    return Response(content="Runtime package not found", status_code=404)


