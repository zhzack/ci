INSTALL_PS1_TEMPLATE = r"""#Requires -Version 5.1
# Mini Pipeline runner installer (Windows) & Daemon Setup. Generated by the platform.
$ErrorActionPreference = 'Stop'
$Server = if ($env:MINI_PIPELINE_SERVER) { $env:MINI_PIPELINE_SERVER } else { '__SERVER_URL__' }
$Token  = if ($env:MINI_PIPELINE_TOKEN) { $env:MINI_PIPELINE_TOKEN } else { '__TOKEN__' }
$Force  = if ($env:MINI_PIPELINE_FORCE -eq '1' -or $env:MINI_PIPELINE_FORCE -eq 'true') {
    $true
} else {
    $false
}
$Root   = Join-Path $env:USERPROFILE '.mini-pipeline-runner'
$Workspace = Join-Path $Root 'workspace'
$Runner = Join-Path $Root 'venv\Scripts\mini-pipeline-runner.exe'
$PythonExe = Join-Path $Root 'venv\Scripts\python.exe'

Write-Host "==> Mini Pipeline Runner 部署程序 (目标服务: $Server)"

New-Item -ItemType Directory -Force -Path $Root | Out-Null
New-Item -ItemType Directory -Force -Path $Workspace | Out-Null

$isInstalled = (Test-Path $Runner) -and (Test-Path $PythonExe)

if ($isInstalled -and (-not $Force)) {
    Write-Host "==> [✓] 检测到已存在安装 ($Root)，跳过重复环境初始化与依赖安装。"
} else {
    $python = Get-Command python -ErrorAction SilentlyContinue
    if (-not $python) {
        Write-Error 'Python 3.9+ is required. 请先安装 Python 3.9+ 并勾选 Add to PATH。'
        exit 1
    }

    if (-not (Test-Path (Join-Path $Root 'venv'))) {
        Write-Host '==> 正在初始化 Python 虚拟运行环境...'
        & python -m venv (Join-Path $Root 'venv')
    }

    Write-Host '==> 正在从服务端下载平台运行包...'
    $Pkg = Join-Path $env:TEMP ('mini-pipeline-' + [guid]::NewGuid().ToString('N') + '.tar.gz')
    try {
        Invoke-WebRequest -Uri ($Server + '/install/package.tar.gz') -OutFile $Pkg -UseBasicParsing
    } catch {
        Write-Error ("下载平台运行包失败: " + $_.Exception.Message)
        exit 1
    }

    Write-Host '==> 正在安装/升级 mini-pipeline runner 依赖...'
    & $PythonExe -m pip install --quiet --upgrade $Pkg
    Remove-Item $Pkg -ErrorAction SilentlyContinue

    if (-not (Test-Path $Runner)) {
        Write-Error 'Runner 可执行程序未正确安装。'
        exit 1
    }
    Write-Host '==> [✓] Mini Pipeline Runner 核心组件安装就绪！'
}

# 1. 写入持久化配置文件
$ConfigJson = @{
    server = $Server
    token = $Token
    workspace = $Workspace
    installed_at = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
} | ConvertTo-Json
Set-Content -Path (Join-Path $Root 'config.json') -Value $ConfigJson -Force

# 2. 生成后台运行脚本与开机自启动配置
$LauncherBat = Join-Path $Root 'start-runner.bat'
$LauncherVbs = Join-Path $Root 'start-runner-background.vbs'
$LogFile = Join-Path $Root 'runner.log'

$BatContent = "@echo off`r`ncd /d `"$Root`"`r`n:RUNNER_LOOP`r`n" + `
    "echo [%date% %time%] 正在启动 Mini Pipeline Runner... >> `"$LogFile`"`r`n" + `
    "`"$Runner`" --server `"$Server`" --token `"$Token`" " + `
    "--workspace `"$Workspace`" >> `"$LogFile`" 2>&1`r`n" + `
    "echo [%date% %time%] Runner 退出，将在 5 秒后自动重连... >> `"$LogFile`"`r`n" + `
    "timeout /t 5 /nobreak >nul`r`n" + `
    "goto RUNNER_LOOP"
Set-Content -Path $LauncherBat -Value $BatContent -Force -Encoding ASCII

$VbsContent = "Set WshShell = CreateObject(`"WScript.Shell`")`r`n" + `
    "WshShell.Run `"`"`"`" & `"$LauncherBat`" & `"`"`"`", 0, False"
Set-Content -Path $LauncherVbs -Value $VbsContent -Force -Encoding ASCII

# 3. 注册到 Windows 开机自启文件夹 (Startup)
$StartupFolder = [Environment]::GetFolderPath('Startup')
if (Test-Path $StartupFolder) {
    $StartupLink = Join-Path $StartupFolder 'MiniPipelineRunner.vbs'
    Copy-Item $LauncherVbs $StartupLink -Force -ErrorAction SilentlyContinue
    Write-Host "==> [✓] 已注册 Windows 开机自启动守护任务 ($StartupLink)"
}

# 4. 自动检测并开启 Windows 官方 OpenSSH Server 服务端
$SshStatus = "未安装"
$p = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
$isAdmin = $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

try {
    $sshd = Get-Service -Name 'sshd' -ErrorAction SilentlyContinue
    if (-not $sshd) {
        if ($isAdmin) {
            Write-Host "==> 正在自动安装 Windows 官方 OpenSSH.Server 功能组件..."
            Add-WindowsCapability -Online -Name OpenSSH.Server~~~~0.0.1.0 `
                -ErrorAction SilentlyContinue | Out-Null
            $sshd = Get-Service -Name 'sshd' -ErrorAction SilentlyContinue
        }
    }
    if ($sshd) {
        if ($sshd.Status -ne 'Running') {
            if ($isAdmin) {
                Start-Service sshd -ErrorAction SilentlyContinue
                Set-Service -Name sshd -StartupType 'Automatic' -ErrorAction SilentlyContinue
                New-NetFirewallRule -Name 'OpenSSH-Server-In-TCP' `
                    -DisplayName 'OpenSSH Server (sshd)' -Enabled True `
                    -Direction Inbound -Protocol TCP -Action Allow -LocalPort 22 `
                    -ErrorAction SilentlyContinue | Out-Null
            } else {
                Start-Service sshd -ErrorAction SilentlyContinue
            }
        }
        $sshd = Get-Service -Name 'sshd' -ErrorAction SilentlyContinue
        if ($sshd -and $sshd.Status -eq 'Running') {
            $SshStatus = "已就绪 (端口 22, 服务运行中)"
            Write-Host "==> [✓] Windows OpenSSH Server 服务已成功启动并配置开机自启！"
        } else {
            $SshStatus = "已安装但未运行 (需管理员权限启动: Start-Service sshd)"
        }
    } else {
        $SshStatus = "未安装 (以管理员身份运行部署指令可自动一键安装开启)"
    }
} catch {
    $SshStatus = "检测/开启异常"
}

# 5. 停止已有旧进程并立即启动后台 Runner
if ($Token) {
    Write-Host "==> 正在启动 Mini Pipeline Runner 后台进程..."
    Get-Process | Where-Object {
        $_.Path -like "*mini-pipeline-runner*"
    } | Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Process "wscript.exe" -ArgumentList "`"$LauncherVbs`"" -WindowStyle Hidden
    Start-Sleep -Seconds 1
    Write-Host ""
    Write-Host "=================================================================="
    Write-Host " [✓] Mini Pipeline Runner 部署成功并已在后台常驻运行！"
    Write-Host " [*] 开机自启: 已配置 (系统登录后自动后台启动)"
    Write-Host " [*] SSH 服务: $SshStatus"
    Write-Host " [*] 运行日志: $LogFile"
    Write-Host " [*] 快捷卸载: powershell -c `"irm $Server/uninstall.ps1 | iex`""
    Write-Host "=================================================================="
} else {
    Write-Host "==> 未提供 Token，可手动通过命令行启动: $LauncherBat"
}
"""

