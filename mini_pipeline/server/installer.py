"""Self-service installer endpoints.

The platform serves its own bootstrap scripts so a fresh machine can be
set up with ONE command (no repo clone, no manual steps):

    Windows PowerShell:  irm http://<server>:8000/install.ps1 | iex
    Linux / macOS:       curl -fsSL http://<server>:8000/install.sh | bash

The scripts auto-detect Python, create a dedicated venv, download the
platform package from this server, install the runner, and — when the
``MINI_PIPELINE_TOKEN`` environment variable is preset (the Machines page
generates the full one-liner including it) — start the agent immediately.

The endpoints are public by design: bootstrapping happens *before* the
machine has any token. The package tarball contains the platform's own
code; if that is sensitive in your environment, put a gateway rule in
front of ``/install/*``.
"""

from __future__ import annotations

import tarfile
from pathlib import Path

from fastapi import APIRouter, Request
from fastapi.responses import Response

installer_router = APIRouter(tags=["system"], include_in_schema=True)

_PACKAGE_ROOT = Path(__file__).resolve().parents[2]
_TARBALL_EXCLUDE_PARTS = {
    "__pycache__", ".venv", "venv", "node_modules", "data", ".git",
    "frontend", "tests", "docs", "examples", "toolhub", "scripts",
    ".vscode", ".pytest_cache", ".ruff_cache",
}

INSTALL_PS1_TEMPLATE = r"""#Requires -Version 5.1
# Mini Pipeline runner installer (Windows). Generated by the platform.
$ErrorActionPreference = 'Stop'
$Server = if ($env:MINI_PIPELINE_SERVER) { $env:MINI_PIPELINE_SERVER } else { '__SERVER_URL__' }
$Token  = if ($env:MINI_PIPELINE_TOKEN) { $env:MINI_PIPELINE_TOKEN } else { '__TOKEN__' }
$Root   = Join-Path $env:USERPROFILE '.mini-pipeline-runner'

Write-Host "==> Mini Pipeline installer (server: $Server)"
$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) {
    Write-Error 'Python 3.9+ is required but was not found on PATH'
    exit 1
}

New-Item -ItemType Directory -Force -Path $Root | Out-Null
if (-not (Test-Path (Join-Path $Root 'venv'))) {
    Write-Host '==> Creating virtual environment'
    & python -m venv (Join-Path $Root 'venv')
}
$Pip = Join-Path $Root 'venv\Scripts\python.exe'

Write-Host '==> Downloading platform package'
$Pkg = Join-Path $env:TEMP ('mini-pipeline-' + [guid]::NewGuid().ToString('N') + '.tar.gz')
Invoke-WebRequest -Uri ($Server + '/install/package.tar.gz') -OutFile $Pkg -UseBasicParsing

Write-Host '==> Installing mini-pipeline'
& $Pip -m pip install --quiet --upgrade $Pkg
Remove-Item $Pkg -ErrorAction SilentlyContinue

$Runner = Join-Path $Root 'venv\Scripts\mini-pipeline-runner.exe'
if (-not (Test-Path $Runner)) {
    Write-Error 'Runner executable was not installed'
    exit 1
}

Write-Host ''
Write-Host 'Installed. Start the runner with:'
$Workspace = Join-Path $Root 'workspace'
Write-Host ("  {0} --server {1} --token <mrt_...> --workspace {2}" -f $Runner, $Server, $Workspace)
if ($Token) {
    Write-Host '==> MINI_PIPELINE_TOKEN detected - starting the runner now (Ctrl+C to stop)'
    & $Runner --server $Server --token $Token --workspace $Workspace
}
"""

INSTALL_SH_TEMPLATE = r"""#!/bin/sh
# Mini Pipeline runner installer (Linux/macOS). Generated by the platform.
set -eu
SERVER="${MINI_PIPELINE_SERVER:-__SERVER_URL__}"
TOKEN="${MINI_PIPELINE_TOKEN:-__TOKEN__}"
ROOT="${HOME}/.mini-pipeline-runner"

echo "==> Mini Pipeline installer (server: ${SERVER})"
mkdir -p "$ROOT"

PYTHON=""
# 1. Probe local python
for c in python3 python; do
  command -v "$c" >/dev/null 2>&1 || continue
  "$c" -c 'import sys; assert sys.version_info >= (3,9)' >/dev/null 2>&1 || continue
  PYTHON="$c" && break
done

# 2. If python not found or missing venv, auto-install via package manager or standalone runtime
if [ -z "$PYTHON" ] || ! "$PYTHON" -m venv "$ROOT/.test_venv" >/dev/null 2>&1; then
  rm -rf "$ROOT/.test_venv" >/dev/null 2>&1 || true
  echo "==> 检测到系统缺少就绪的 Python 虚拟环境，正在尝试自适应自动装配..."
  
  if command -v apt-get >/dev/null 2>&1 && [ "$(id -u)" -eq 0 ]; then
    echo "==> 使用 apt 自动安装 python3-venv 与 python3-pip..."
    apt-get update -y >/dev/null 2>&1 || true
    apt-get install -y python3-venv python3-pip >/dev/null 2>&1 || true
    for c in python3 python; do
      command -v "$c" >/dev/null 2>&1 || continue
      "$c" -c 'import sys; assert sys.version_info >= (3,9)' >/dev/null 2>&1 || continue
      PYTHON="$c" && break
    done
  elif command -v yum >/dev/null 2>&1 && [ "$(id -u)" -eq 0 ]; then
    echo "==> 使用 yum 自动安装 python3-pip..."
    yum install -y python3-pip python3 >/dev/null 2>&1 || true
    for c in python3 python; do
      command -v "$c" >/dev/null 2>&1 || continue
      "$c" -c 'import sys; assert sys.version_info >= (3,9)' >/dev/null 2>&1 || continue
      PYTHON="$c" && break
    done
  fi
fi

# 3. Create or verify venv (ensure both python and pip are ready)
if [ ! -x "$ROOT/venv/bin/python" ] || [ ! -x "$ROOT/venv/bin/pip" ]; then
  echo "==> Initializing virtual environment in $ROOT/venv"
  rm -rf "$ROOT/venv" >/dev/null 2>&1 || true
  if [ -n "$PYTHON" ] && "$PYTHON" -m venv "$ROOT/venv" >/dev/null 2>&1; then
    echo "==> 成功使用系统 Python 创建虚拟环境"
  else
    echo "==> 正在尝试装配独立 Python 运行时..."
    ARCH="$(uname -m)"
    RUNTIME_PKG="python-standalone-linux-${ARCH}.tar.gz"
    DL_URL="${SERVER}/install/runtimes/${RUNTIME_PKG}"
    if curl -fsSL "$DL_URL" -o "$ROOT/${RUNTIME_PKG}" 2>/dev/null; then
      mkdir -p "$ROOT/python"
      tar -xzf "$ROOT/${RUNTIME_PKG}" -C "$ROOT/python" --strip-components=1 2>/dev/null \
        || tar -xzf "$ROOT/${RUNTIME_PKG}" -C "$ROOT/python"
      rm -f "$ROOT/${RUNTIME_PKG}"
      PYTHON="$ROOT/python/bin/python3"
      "$PYTHON" -m venv "$ROOT/venv" || cp -r "$ROOT/python" "$ROOT/venv"
    fi
  fi
fi

if [ -x "$ROOT/venv/bin/pip" ]; then
  PIP_CMD="$ROOT/venv/bin/pip"
elif [ -x "$ROOT/venv/bin/python" ]; then
  PIP_CMD="$ROOT/venv/bin/python -m pip"
else
  echo "ERROR: 无法创建 Python 环境。" >&2
  echo "请执行: apt update && apt install -y python3-venv python3-pip" >&2
  exit 1
fi

echo "==> Downloading platform package"
PKG=$(mktemp /tmp/mini-pipeline-XXXXXX.tar.gz)
curl -fsSL "${SERVER}/install/package.tar.gz" -o "$PKG"

echo "==> Installing mini-pipeline"
$PIP_CMD install --quiet --upgrade "$PKG"
rm -f "$PKG"

RUNNER="$ROOT/venv/bin/mini-pipeline-runner"
echo ""
echo "Installed. Start the runner with:"
echo "  $RUNNER --server $SERVER --token <mrt_...> --workspace $ROOT/workspace"
if [ -n "$TOKEN" ]; then
  echo "==> MINI_PIPELINE_TOKEN detected - starting the runner now (Ctrl+C to stop)"
  exec "$RUNNER" --server "$SERVER" --token "$TOKEN" --workspace "$ROOT/workspace"
fi
"""


def _server_base_url(request: Request) -> str:
    forwarded = request.headers.get("x-forwarded-proto")
    scheme = forwarded or request.url.scheme
    host = request.headers.get("x-forwarded-host") or request.headers.get("host")
    if host:
        return f"{scheme}://{host}"
    return str(request.base_url).rstrip("/")


def _build_package_tarball() -> bytes:
    """Tar.gz of the platform package (mini_pipeline/ + pyproject.toml)."""
    import io

    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as tar:
        pyproject = _PACKAGE_ROOT / "pyproject.toml"
        tar.add(pyproject, arcname="pyproject.toml")
        package_dir = _PACKAGE_ROOT / "mini_pipeline"
        for path in sorted(package_dir.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(_PACKAGE_ROOT)
            if any(part in _TARBALL_EXCLUDE_PARTS for part in relative.parts):
                continue
            if path.name == ".DS_Store":
                continue
            tar.add(path, arcname=relative.as_posix())
    return buffer.getvalue()


@installer_router.get("/install/package.tar.gz", include_in_schema=False)
def install_package() -> Response:
    payload = _build_package_tarball()
    return Response(
        content=payload,
        media_type="application/gzip",
        headers={"Content-Disposition": 'attachment; filename="mini-pipeline.tar.gz"'},
    )


@installer_router.get("/install/runtimes/{filename}", include_in_schema=False)
def get_runtime_package(filename: str) -> Response:
    """Serve runtime packages from storage/environments/ or package hub."""
    pkg_dir = _PACKAGE_ROOT / "data" / "storage" / "environments"
    file_path = pkg_dir / filename
    if file_path.is_file():
        return Response(
            content=file_path.read_bytes(),
            media_type="application/gzip",
            headers={"Content-Disposition": f'attachment; filename="{filename}"'},
        )
    return Response(content="Runtime package not found", status_code=404)


@installer_router.get("/install.sh", include_in_schema=False)
def install_sh(request: Request, token: str = "") -> Response:
    script = (
        INSTALL_SH_TEMPLATE
        .replace("__SERVER_URL__", _server_base_url(request))
        .replace("__TOKEN__", token)
    )
    return Response(content=script, media_type="text/x-shellscript")


@installer_router.get("/install.ps1", include_in_schema=False)
def install_ps1(request: Request, token: str = "") -> Response:
    script = (
        INSTALL_PS1_TEMPLATE
        .replace("__SERVER_URL__", _server_base_url(request))
        .replace("__TOKEN__", token)
    )
    return Response(
        content=script,
        media_type="text/plain",
        headers={"Content-Disposition": 'inline; filename="install.ps1"'},
    )


@installer_router.get("/install", include_in_schema=False)
def install_universal(request: Request, token: str = "") -> Response:
    """Auto-detect client platform/shell from User-Agent and serve the script."""
    user_agent = request.headers.get("user-agent", "").lower()
    if "powershell" in user_agent or "pwsh" in user_agent:
        return install_ps1(request, token=token)
    return install_sh(request, token=token)


UNINSTALL_SH_TEMPLATE = r"""#!/bin/sh
# Mini Pipeline runner & environment uninstaller (Linux/macOS).
set -eu
ROOT="${HOME}/.mini-pipeline-runner"

echo "==> Mini Pipeline uninstaller"
echo "==> 正在终止运行中的 Mini Pipeline Runner 进程..."
pkill -f "mini-pipeline-runner" 2>/dev/null || true

if [ -d "$ROOT" ]; then
  echo "==> 正在清理所有运行时环境与工作区目录: $ROOT..."
  rm -rf "$ROOT"
  echo "==> 清理完成！所有已安装环境、Runner 节点与工作区已彻底卸载。"
else
  echo "==> 未检测到安装目录 $ROOT，无需清理。"
fi
"""

UNINSTALL_PS1_TEMPLATE = r"""#Requires -Version 5.1
# Mini Pipeline runner & environment uninstaller (Windows).
$ErrorActionPreference = 'SilentlyContinue'
$Root = Join-Path $env:USERPROFILE '.mini-pipeline-runner'

Write-Host "==> Mini Pipeline uninstaller"
Write-Host "==> 正在终止运行中的 Mini Pipeline Runner 进程..."
Get-Process | Where-Object { $_.ProcessName -like "*mini-pipeline-runner*" } | Stop-Process -Force

if (Test-Path $Root) {
    Write-Host "==> 正在清理所有运行时环境与工作区目录: $Root..."
    Remove-Item -Recurse -Force $Root
    Write-Host "==> 清理完成！所有已安装环境、Runner 节点与工作区已彻底卸载。"
} else {
    Write-Host "==> 未检测到安装目录 $Root，无需清理。"
}
"""


@installer_router.get("/uninstall.sh", include_in_schema=False)
def uninstall_sh() -> Response:
    return Response(content=UNINSTALL_SH_TEMPLATE, media_type="text/x-shellscript")


@installer_router.get("/uninstall.ps1", include_in_schema=False)
def uninstall_ps1() -> Response:
    return Response(
        content=UNINSTALL_PS1_TEMPLATE,
        media_type="text/plain",
        headers={"Content-Disposition": 'inline; filename="uninstall.ps1"'},
    )


@installer_router.get("/uninstall", include_in_schema=False)
def uninstall_universal(request: Request) -> Response:
    """Auto-detect client platform/shell from User-Agent and serve the uninstall script."""
    user_agent = request.headers.get("user-agent", "").lower()
    if "powershell" in user_agent or "pwsh" in user_agent:
        return uninstall_ps1()
    return uninstall_sh()


